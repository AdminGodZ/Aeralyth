// Builds a folder ZIP from independent tasks. Helper workers (or, without
// them, this thread) turn sources into finished archive pieces; this module
// only schedules the tasks and assembles the pieces in source order.
import { archiveCompressionLevel } from "@/features/archive/compression-policy";
import { crc32Combine } from "@/features/archive/crc32";
import {
  instantiateRawDeflater,
  type RawDeflater,
  supportsNativeRawDeflate,
  verifyRawDeflater,
} from "@/features/archive/raw-deflate";
import {
  encodeCentralDirectory,
  encodeLocalFileHeader,
  encodeZipEntryName,
  ZIP_METHOD_DEFLATE,
  ZIP_METHOD_STORE,
  type ZipCompressionMethod,
  type ZipEntryHeader,
} from "@/features/archive/zip-container";
import type {
  FolderZipWorkerRequest,
  FolderZipWorkerResponse,
} from "@/features/dashboard/folder-zip-messages";
import {
  createFolderZipAdmission,
  FOLDER_ZIP_REFERENCE_BYTES,
  FOLDER_ZIP_TASK_BYTES,
  type FolderZipAdmission,
  type FolderZipCodec,
  type FolderZipPlanTask,
  folderZipTaskCost,
  folderZipWorkerCount,
  planFolderZipTasks,
} from "@/features/dashboard/folder-zip-plan";
import {
  createFolderZipSink,
  type FolderZipSinkRange,
} from "@/features/dashboard/folder-zip-sink";
import {
  FOLDER_ZIP_BATCH_META_FIELDS,
  FOLDER_ZIP_BATCH_REFERENCE,
  type FolderZipHelperRequest,
  type FolderZipHelperResponse,
  type FolderZipTask,
  type FolderZipTaskContext,
  type FolderZipTaskResult,
  runFolderZipTask,
} from "@/features/dashboard/folder-zip-tasks";
import { ZIP_ARCHIVE_SAFETY_LIMIT_ERROR } from "@/features/dashboard/zip-archive-limit";

export type FolderZipProgress = Extract<
  FolderZipWorkerResponse,
  { type: "progress" }
>;

export type FolderZipHelperPort = {
  post(message: FolderZipHelperRequest): void;
  terminate(): void;
};

export type FolderZipHelperListener = {
  message(message: FolderZipHelperResponse): void;
  /** The helper failed to load or crashed. */
  failure(): void;
};

export type FolderZipEnvironment = {
  hardwareConcurrency?: number;
  /** Loads the zlib WebAssembly module; a rejection selects the native codec. */
  loadWasm?: () => Promise<ArrayBuffer>;
  /** Starts a helper worker. Absent when workers cannot be nested. */
  spawnHelper?: (listener: FolderZipHelperListener) => FolderZipHelperPort;
  helperStartupTimeoutMs?: number;
  taskBytes?: number;
};

type Entry = {
  path: string;
  name: Uint8Array;
  directory: boolean;
  file: Blob | null;
  size: number;
  lastModified: number;
  level: number;
  crc32: number;
  compressedSize: number;
  method: ZipCompressionMethod;
  /** Archive piece that holds the entry, and the entry's offset inside it. */
  unit: number;
  unitOffset: number;
};

/** A source Blob referenced by the archive, or generated bytes in the sink. */
type Part = Blob | FolderZipSinkRange;

type Unit = { parts: Part[]; bytes: number };

/** Assembly state of an entry that spans several tasks. */
type LargeEntry = {
  unit: number;
  pendingTasks: number;
  checksums: number[];
  lengths: number[];
  outputs: FolderZipSinkRange[];
  outputBytes: number;
};

const HELPER_STARTUP_TIMEOUT_MS = 10_000;
const HELPER_FAILURE_ERROR = "The ZIP helper worker stopped unexpectedly.";

export async function createFolderZipArchive(
  request: Extract<FolderZipWorkerRequest, { type: "compress" }>,
  {
    signal,
    onProgress,
    environment = {},
  }: {
    signal?: AbortSignal;
    onProgress?(progress: FolderZipProgress): void;
    environment?: FolderZipEnvironment;
  } = {},
): Promise<Blob> {
  const { compressionMode = "balanced", maxOutputBytes } = request;
  if (
    maxOutputBytes !== undefined &&
    (!Number.isSafeInteger(maxOutputBytes) || maxOutputBytes <= 0)
  ) {
    throw new Error("The ZIP archive output limit is invalid.");
  }
  const taskBytes = environment.taskBytes ?? FOLDER_ZIP_TASK_BYTES;

  const entries: Entry[] = [];
  const paths = new Set<string>();
  let totalBytes = 0;
  for (const source of request.sources) {
    const normalized = normalizeArchivePath(source.path);
    if (!normalized) continue;
    const path = source.directory ? `${normalized}/` : normalized;
    if (paths.has(path)) {
      throw new Error(`Two entries resolve to the same ZIP path: ${path}`);
    }
    paths.add(path);
    const file = source.directory ? null : source.file;
    const lastModified = source.directory
      ? source.lastModified
      : source.file.lastModified;
    entries.push({
      path,
      name: encodeZipEntryName(path),
      directory: source.directory === true,
      file,
      size: file?.size ?? 0,
      lastModified: Number.isFinite(lastModified) ? lastModified : Date.now(),
      level: file?.size
        ? archiveCompressionLevel({
            path,
            mimeType: file.type,
            mode: compressionMode,
          })
        : 0,
      crc32: 0,
      compressedSize: 0,
      method: ZIP_METHOD_STORE,
      unit: -1,
      unitOffset: 0,
    });
    totalBytes += file?.size ?? 0;
  }

  let processedBytes = 0;
  const reportProgress = (currentPath: string) =>
    onProgress?.({ type: "progress", processedBytes, totalBytes, currentPath });
  reportProgress("");

  let wasm: ArrayBuffer | null = null;
  let deflater: RawDeflater | null = null;
  let codec: FolderZipCodec = "none";
  if (entries.some((entry) => entry.level > 0)) {
    try {
      const bytes = await environment.loadWasm?.();
      if (bytes) {
        const candidate = await instantiateRawDeflater(bytes);
        if (await verifyRawDeflater(candidate)) {
          wasm = bytes;
          deflater = candidate;
        }
      }
    } catch {
      // Fall through to the native codec.
    }
    signal?.throwIfAborted();
    codec = deflater ? "wasm" : supportsNativeRawDeflate() ? "native" : "none";
    if (codec === "none") {
      for (const entry of entries) entry.level = 0;
    }
  }

  const plan = planFolderZipTasks(entries, { codec, taskBytes });
  const units: Unit[] = [];
  const unitOfTask = new Map<FolderZipPlanTask, number>();
  const largeEntries = new Map<number, LargeEntry>();
  for (const task of plan) {
    if (task.kind === "batch") {
      unitOfTask.set(task, units.push({ parts: [], bytes: 0 }) - 1);
      continue;
    }
    let large = largeEntries.get(task.entry);
    if (!large) {
      large = {
        unit: units.push({ parts: [], bytes: 0 }) - 1,
        pendingTasks: 0,
        checksums: [],
        lengths: [],
        outputs: [],
        outputBytes: 0,
      };
      largeEntries.set(task.entry, large);
    }
    large.pendingTasks += 1;
  }

  let outputBytes = 0;
  const account = (bytes: number) => {
    outputBytes += bytes;
    if (maxOutputBytes !== undefined && outputBytes > maxOutputBytes) {
      throw new Error(ZIP_ARCHIVE_SAFETY_LIMIT_ERROR);
    }
  };
  const workerCount = environment.spawnHelper
    ? folderZipWorkerCount({
        hardwareConcurrency: environment.hardwareConcurrency,
        requested: request.maxWorkers,
        tasks: plan.length,
      })
    : 0;
  const admission = createFolderZipAdmission({
    maxTasks: Math.max(1, workerCount),
  });
  const scheduler: { wake(): void; fail(error: unknown): void } = {
    wake() {},
    fail() {},
  };
  const sink = createFolderZipSink({
    onQueued: (bytes) => admission.hold(bytes),
    onWritten(bytes) {
      admission.unhold(bytes);
      scheduler.wake();
    },
    onError: (error) => scheduler.fail(error),
  });

  const buildTask = (index: number): FolderZipTask => {
    const task = plan[index];
    if (task.kind === "batch") {
      return {
        kind: "batch",
        id: index,
        referenceBytes: FOLDER_ZIP_REFERENCE_BYTES,
        entries: entries
          .slice(task.first, task.first + task.count)
          .map(({ path, directory, file, size, lastModified, level }) => ({
            path,
            directory,
            file,
            size,
            lastModified,
            level,
          })),
      };
    }
    const entry = entries[task.entry];
    const file = entry.file as Blob;
    return task.kind === "range"
      ? {
          kind: "range",
          id: index,
          path: entry.path,
          file,
          start: task.start,
          end: task.end,
          level: entry.level,
          final: task.final,
        }
      : { kind: "stream", id: index, path: entry.path, file };
  };

  const applyBatch = (
    task: Extract<FolderZipPlanTask, { kind: "batch" }>,
    result: Extract<FolderZipTaskResult, { kind: "batch" }>,
  ) => {
    const segment = new Uint8Array(result.segment);
    const unitIndex = unitOfTask.get(task) as number;
    const unit = units[unitIndex];
    let runStart = 0;
    const pushRun = (end: number) => {
      if (end === runStart) return;
      unit.parts.push(sink.write(segment.subarray(runStart, end)));
      runStart = end;
    };
    for (let index = 0; index < task.count; index++) {
      const entry = entries[task.first + index];
      const [checksum, compressedSize, flags, headerOffset, headerSize] =
        result.meta.subarray(
          index * FOLDER_ZIP_BATCH_META_FIELDS,
          (index + 1) * FOLDER_ZIP_BATCH_META_FIELDS,
        );
      entry.crc32 = checksum;
      entry.compressedSize = compressedSize;
      entry.method =
        (flags & 0xff) === ZIP_METHOD_DEFLATE
          ? ZIP_METHOD_DEFLATE
          : ZIP_METHOD_STORE;
      entry.unit = unitIndex;
      entry.unitOffset = unit.bytes;
      unit.bytes += headerSize + compressedSize;
      if (flags & FOLDER_ZIP_BATCH_REFERENCE) {
        pushRun(headerOffset + headerSize);
        unit.parts.push(entry.file as Blob);
      }
    }
    pushRun(segment.length);
    account(unit.bytes);
  };

  const finishLargeEntry = (entryIndex: number, large: LargeEntry) => {
    const entry = entries[entryIndex];
    const unit = units[large.unit];
    entry.unit = large.unit;
    if (entry.level > 0) {
      entry.method = ZIP_METHOD_DEFLATE;
      entry.compressedSize = large.outputBytes;
    } else {
      // The archive refers to the source bytes instead of holding a copy.
      entry.method = ZIP_METHOD_STORE;
      entry.compressedSize = entry.size;
      account(entry.size);
    }
    const header = encodeLocalFileHeader(headerOf(entry));
    account(header.length);
    unit.parts = [
      sink.write(header),
      ...(entry.level > 0 ? large.outputs : [entry.file as Blob]),
    ];
    unit.bytes = header.length + entry.compressedSize;
  };

  const applyPart = (index: number, part: ArrayBuffer) => {
    const task = plan[index];
    if (task.kind !== "stream") return;
    const large = largeEntries.get(task.entry) as LargeEntry;
    large.outputs.push(sink.write(new Uint8Array(part)));
    large.outputBytes += part.byteLength;
    account(part.byteLength);
  };

  /** Drops the output of a stream task that has to start over. */
  const discardParts = (index: number) => {
    const task = plan[index];
    if (task.kind !== "stream") return;
    const large = largeEntries.get(task.entry) as LargeEntry;
    outputBytes -= large.outputBytes;
    large.outputs = [];
    large.outputBytes = 0;
  };

  const applyResult = (index: number, result: FolderZipTaskResult) => {
    const task = plan[index];
    if (task.kind !== result.kind || result.id !== index) {
      throw new Error("A ZIP helper returned an unexpected result.");
    }
    if (task.kind === "batch") {
      applyBatch(
        task,
        result as Extract<FolderZipTaskResult, { kind: "batch" }>,
      );
      processedBytes += task.bytes;
      reportProgress(entries[task.first + task.count - 1].path);
      return;
    }
    const entry = entries[task.entry];
    const large = largeEntries.get(task.entry) as LargeEntry;
    if (task.kind === "range" && result.kind === "range") {
      const length = task.end - task.start;
      large.checksums[task.index] = result.crc32;
      large.lengths[task.index] = length;
      if (result.output) {
        large.outputs[task.index] = sink.write(new Uint8Array(result.output));
        large.outputBytes += result.output.byteLength;
        account(result.output.byteLength);
      }
      large.pendingTasks -= 1;
      if (large.pendingTasks === 0) {
        // Ranges finish in any order; fold their checksums front to back.
        entry.crc32 = large.checksums.reduce(
          (checksum, rangeChecksum, range) =>
            crc32Combine(checksum, rangeChecksum, large.lengths[range]),
          0,
        );
        finishLargeEntry(task.entry, large);
      }
      processedBytes += length;
    } else if (result.kind === "stream") {
      entry.crc32 = result.crc32;
      large.pendingTasks = 0;
      finishLargeEntry(task.entry, large);
      processedBytes += entry.size;
    }
    reportProgress(entry.path);
  };

  let sinkBlob: Blob;
  try {
    await runTasks({
      taskCount: plan.length,
      workerCount,
      admission,
      scheduler,
      cost: (index) => folderZipTaskCost(plan[index], entries, taskBytes),
      buildTask,
      applyResult,
      applyPart,
      discardParts,
      signal,
      environment,
      wasm,
      deflater,
      nativeDeflate: codec === "native",
    });
    if (processedBytes !== totalBytes) {
      throw new Error("The ZIP archive is incomplete.");
    }

    let offset = 0;
    const unitOffsets = units.map((unit) => {
      const start = offset;
      offset += unit.bytes;
      return start;
    });
    const directory = encodeCentralDirectory(
      entries.map((entry) => ({
        ...headerOf(entry),
        offset: unitOffsets[entry.unit] + entry.unitOffset,
      })),
      offset,
    );
    account(directory.length);
    units.push({ parts: [sink.write(directory)], bytes: directory.length });
    sinkBlob = await sink.close();
    signal?.throwIfAborted();
  } catch (error) {
    sink.abort(error);
    throw error;
  }

  // Compose the archive in source order from the parked bytes and the
  // referenced sources. Neighbouring sink ranges collapse into one slice.
  const parts: Blob[] = [];
  let run: FolderZipSinkRange | null = null;
  const flushRun = () => {
    if (run) parts.push(sinkBlob.slice(run.start, run.end));
    run = null;
  };
  for (const unit of units) {
    for (const part of unit.parts) {
      if (part instanceof Blob) {
        flushRun();
        parts.push(part);
      } else if (run && run.end === part.start) {
        run.end = part.end;
      } else {
        flushRun();
        run = { ...part };
      }
    }
  }
  flushRun();
  return new Blob(parts, { type: "application/zip" });
}

function headerOf(entry: Entry): ZipEntryHeader {
  return {
    name: entry.name,
    directory: entry.directory,
    method: entry.method,
    level: entry.level,
    crc32: entry.crc32,
    compressedSize: entry.compressedSize,
    uncompressedSize: entry.size,
    lastModified: entry.lastModified,
  };
}

type Helper = {
  port: FolderZipHelperPort;
  /** Index of the task the helper is running. */
  task: number | null;
  alive: boolean;
  startupTimer: ReturnType<typeof setTimeout> | null;
};

function runTasks({
  taskCount,
  workerCount,
  admission,
  scheduler,
  cost,
  buildTask,
  applyResult,
  applyPart,
  discardParts,
  signal,
  environment,
  wasm,
  deflater,
  nativeDeflate,
}: {
  taskCount: number;
  workerCount: number;
  admission: FolderZipAdmission;
  /** Lets the caller resume scheduling or fail the run from outside. */
  scheduler: { wake(): void; fail(error: unknown): void };
  cost(index: number): number;
  buildTask(index: number): FolderZipTask;
  applyResult(index: number, result: FolderZipTaskResult): void;
  applyPart(index: number, part: ArrayBuffer): void;
  discardParts(index: number): void;
  signal: AbortSignal | undefined;
  environment: FolderZipEnvironment;
  wasm: ArrayBuffer | null;
  deflater: RawDeflater | null;
  nativeDeflate: boolean;
}): Promise<void> {
  return new Promise((resolve, reject) => {
    const helpers: Helper[] = [];
    const retries: number[] = [];
    let nextTask = 0;
    let remaining = taskCount;
    let runningInline = false;
    let resumeInline: (() => void) | null = null;
    let settled = false;

    const settle = (error?: unknown) => {
      if (settled) return;
      settled = true;
      signal?.removeEventListener("abort", onAbort);
      for (const helper of helpers) stopHelper(helper);
      resumeInline?.();
      if (error === undefined) resolve();
      else reject(error);
    };
    const onAbort = () =>
      settle(
        signal?.reason ??
          new DOMException("The ZIP archive was canceled.", "AbortError"),
      );
    const stopHelper = (helper: Helper) => {
      helper.alive = false;
      if (helper.startupTimer !== null) clearTimeout(helper.startupTimer);
      helper.startupTimer = null;
      try {
        helper.port.terminate();
      } catch {
        // A helper that is already gone needs no cleanup.
      }
    };
    const peekTask = () =>
      retries.length > 0
        ? retries[retries.length - 1]
        : nextTask < taskCount
          ? nextTask
          : null;
    const takeTask = () => {
      if (retries.length > 0) retries.pop();
      else nextTask += 1;
    };

    const runInline = async () => {
      runningInline = true;
      const context: FolderZipTaskContext = {
        deflater,
        nativeDeflate,
        emitPart: applyPart,
        signal,
      };
      try {
        for (;;) {
          const index = peekTask();
          if (index === null || settled) break;
          const taskCost = cost(index);
          while (!admission.tryAdmit(taskCost)) {
            // Finished output is still being written out; wait for room.
            await new Promise<void>((resume) => {
              resumeInline = resume;
            });
            resumeInline = null;
            if (settled) return;
          }
          takeTask();
          const { result } = await runFolderZipTask(buildTask(index), context);
          if (settled) return;
          admission.release(taskCost);
          applyResult(index, result);
          remaining -= 1;
        }
        settle();
      } catch (error) {
        settle(error);
      }
    };

    const pump = () => {
      if (settled) return;
      if (remaining === 0) {
        settle();
        return;
      }
      const alive = helpers.filter((helper) => helper.alive);
      if (alive.length === 0) {
        // No helper could start, or every helper died: finish on this thread.
        if (!runningInline) void runInline();
        else resumeInline?.();
        return;
      }
      for (const helper of alive) {
        if (helper.task !== null) continue;
        const index = peekTask();
        if (index === null || !admission.tryAdmit(cost(index))) return;
        takeTask();
        helper.task = index;
        try {
          helper.port.post({ type: "helper-task", task: buildTask(index) });
        } catch (error) {
          settle(error);
          return;
        }
      }
    };

    const retire = (helper: Helper) => {
      if (!helper.alive || settled) return;
      stopHelper(helper);
      if (helper.task !== null) {
        discardParts(helper.task);
        admission.release(cost(helper.task));
        retries.push(helper.task);
        helper.task = null;
      }
      pump();
    };

    const onMessage = (helper: Helper, message: FolderZipHelperResponse) => {
      if (!helper.alive || settled) return;
      if (helper.startupTimer !== null) clearTimeout(helper.startupTimer);
      helper.startupTimer = null;
      try {
        if (message.type === "helper-failed") {
          retire(helper);
        } else if (message.type === "helper-error") {
          settle(new Error(message.message || HELPER_FAILURE_ERROR));
        } else if (message.type === "helper-part") {
          if (helper.task === message.id) applyPart(message.id, message.part);
        } else if (message.type === "helper-result") {
          const index = helper.task;
          if (index === null) {
            throw new Error("A ZIP helper returned an unexpected result.");
          }
          helper.task = null;
          admission.release(cost(index));
          applyResult(index, message.result);
          remaining -= 1;
          pump();
        }
      } catch (error) {
        settle(error);
      }
    };

    if (signal?.aborted) {
      onAbort();
      return;
    }
    signal?.addEventListener("abort", onAbort, { once: true });
    scheduler.wake = pump;
    scheduler.fail = settle;

    const { spawnHelper } = environment;
    for (let index = 0; spawnHelper && index < workerCount; index++) {
      const helper: Helper = {
        port: { post() {}, terminate() {} },
        task: null,
        alive: true,
        startupTimer: null,
      };
      try {
        helper.port = spawnHelper({
          message: (message) => onMessage(helper, message),
          failure: () => retire(helper),
        });
        helper.port.post({ type: "helper-init", wasm, nativeDeflate });
      } catch {
        stopHelper(helper);
        continue;
      }
      helper.startupTimer = setTimeout(
        () => retire(helper),
        environment.helperStartupTimeoutMs ?? HELPER_STARTUP_TIMEOUT_MS,
      );
      helpers.push(helper);
    }
    pump();
  });
}

function normalizeArchivePath(value: string) {
  return value
    .replaceAll("\\", "/")
    .split("/")
    .flatMap((segment) => {
      if (!segment || segment === "." || segment === "..") return [];
      const normalized = Array.from(segment)
        .filter((character) => {
          const code = character.charCodeAt(0);
          return code > 31 && code !== 127;
        })
        .join("")
        .trim();
      return normalized ? [normalized] : [];
    })
    .join("/");
}
