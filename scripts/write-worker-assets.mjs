import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedPath = resolve(projectRoot, "src/generated/worker-assets.ts");

const workers = [
  ["VAULT_WORKER_URL", "vault.worker.js"],
  ["FOLDER_ZIP_WORKER_URL", "folder-zip.worker.js"],
];

const generatedExports = await Promise.all(
  workers.map(async ([exportName, fileName]) => {
    const bytes = await readFile(resolve(projectRoot, "public", fileName));
    const fingerprint = createHash("sha256").update(bytes).digest("hex");
    return [
      `export const ${exportName} =`,
      `  "/${fileName}?v=${fingerprint}" as const;`,
    ].join("\n");
  }),
);

const source = [
  "// Generated by `npm run worker:build`. Do not edit manually.",
  ...generatedExports,
  "",
].join("\n");

await mkdir(dirname(generatedPath), { recursive: true });
await writeFile(generatedPath, source, "utf8");
