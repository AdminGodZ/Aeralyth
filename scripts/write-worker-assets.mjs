import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedPath = resolve(projectRoot, "src/generated/worker-assets.ts");
const buildDirectory = resolve(projectRoot, ".worker-build");
const publicDirectory = resolve(projectRoot, "public");
const publicWorkerDirectory = resolve(publicDirectory, "workers");

const workers = [
  ["VAULT_WORKER_URL", "vault"],
  ["FOLDER_ZIP_WORKER_URL", "folder-zip"],
  ["UPLOAD_CHECKSUM_WORKER_URL", "upload-checksum"],
];

await mkdir(publicWorkerDirectory, { recursive: true });
const generatedExports = await Promise.all(
  workers.map(async ([exportName, workerName]) => {
    const bytes = await readFile(
      resolve(buildDirectory, `${workerName}.worker.js`),
    );
    const fingerprint = createHash("sha256").update(bytes).digest("hex");
    const fileName = `${workerName}.${fingerprint}.worker.js`;
    const oldFiles = (await readdir(publicWorkerDirectory)).filter(
      (candidate) =>
        candidate.startsWith(`${workerName}.`) && candidate !== fileName,
    );
    await Promise.all(
      oldFiles.map((candidate) =>
        rm(resolve(publicWorkerDirectory, candidate), { force: true }),
      ),
    );
    await writeFile(resolve(publicWorkerDirectory, fileName), bytes);
    return [
      `export const ${exportName} =`,
      `  "/workers/${fileName}" as const;`,
    ].join("\n");
  }),
);

await Promise.all(
  workers.map(([, workerName]) =>
    rm(resolve(publicDirectory, `${workerName}.worker.js`), { force: true }),
  ),
);
await rm(buildDirectory, { recursive: true, force: true });

const source = [
  "// Generated by `npm run worker:build`. Do not edit manually.",
  ...generatedExports,
  "",
].join("\n");

await mkdir(dirname(generatedPath), { recursive: true });
await writeFile(generatedPath, source, "utf8");
