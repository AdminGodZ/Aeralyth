import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  publishWorkerAsset,
  restoreWorkerAssets,
} from "./worker-asset-store.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const directory = resolve(root, "public/workers");
await mkdir(directory, { recursive: true });
await restoreWorkerAssets(root);

const assets = [
  ["ZIP_CODEC_WORKER_URL", "zip-codec", "worker.js", "zip-web-worker.js"],
  ["ZIP_WASM_URL", "zip-module", "wasm", "zip-module.wasm"],
];
const exports = [];
for (const [name, prefix, extension, source] of assets) {
  const bytes = await readFile(
    fileURLToPath(import.meta.resolve(`@zip.js/zip.js/dist/${source}`)),
  );
  const hash = createHash("sha256").update(bytes).digest("hex");
  const filename = `${prefix}.${hash}.${extension}`;
  await publishWorkerAsset(root, filename, bytes);
  exports.push(`export const ${name} =\n  "/workers/${filename}" as const;`);
}
await mkdir(resolve(root, "src/generated"), { recursive: true });
await writeFile(
  resolve(root, "src/generated/zip-assets.ts"),
  [
    "// Generated by `npm run worker:build`. Do not edit manually.",
    ...exports,
    "",
  ].join("\n"),
);
